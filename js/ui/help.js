function buildHelp() {
  let h = '';
  for (const [title, rows] of SHORTCUTS) {
    h += `<h3>${svgEsc(title)}</h3><table>`;
    for (const [k, d] of rows) h += `<tr><td>${svgEsc(k)}</td><td>${svgEsc(d)}</td></tr>`;
    h += '</table>';
  }
  h += '<p class="foot">Ctrl+N（新規）・Ctrl+W・Ctrl+T はブラウザが使っているので、このアプリでは使えません。新規は上の「新規」ボタンからどうぞ。Mac では Ctrl を ⌘ に読みかえてください。パスファインダーは右のパネルのボタンから使います。</p>';
  $('helpBody').innerHTML = h;
}
function toggleHelp(show) { $('help').hidden = !show; }
$('helpClose').addEventListener('click', () => toggleHelp(false));
$('help').addEventListener('click', (e) => { if (e.target === $('help')) toggleHelp(false); });
